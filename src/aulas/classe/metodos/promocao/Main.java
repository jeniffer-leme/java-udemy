package aulas.classe.metodos.promocao;

public class Main {
    public static void main(String[] args) {
        
        //Variável de tipo primitivo inteiro
        int numA = 25;
        
        //Variável de tipo primitivo double (ponto decimal)
        double numB;
        
        //Promoção automática (ímplicita) de um valor inteiro para um valor double
        numB = numA;
        
        System.out.println(numB);
        
        double resultado = Math.sqrt(numA);
        System.out.println(resultado);
        
        //Divisão inteira
        System.out.println(3/2);
        
        //Divisão fracionária
        System.out.println(3/2);

    }
}
